// ─── Catálogo central de erros ────────────────────────────────────────────────
//
// Fonte única de todos os erros conhecidos da plataforma (site e app).
// Cada código é estável: a API devolve `{ message, code }`, o site e o app
// decidem a reação pelo `code`, e `docs/catalogo-erros.md` é gerado daqui
// (`npx tsx scripts/gerar-catalogo-erros.ts`).
//
// Este arquivo não importa nada de servidor: é usado também no navegador.
//
// Para adicionar um erro: crie a entrada abaixo, use `new AppError("CODIGO")`
// (servidor) ou `apiError("CODIGO")` (rota), e rode o gerador do documento.
// O teste `test/falhas/catalogo.test.ts` falha se um código usado no código
// não existir aqui ou se o documento estiver desatualizado.

export type Dominio =
  | "GERAL"
  | "AUTH"
  | "USUARIO"
  | "AGENDA"
  | "CONSULTA"
  | "PAGAMENTO"
  | "CHAT"
  | "RECEITA"
  | "CERTIFICADO"
  | "ARQUIVO"
  | "PESO"
  | "ADMIN"
  | "VIDEO"
  | "FILA"
  | "REDE"
  | "INFRA";

export type Severidade = "info" | "aviso" | "erro" | "critico";

export interface ErrorDef {
  dominio:         Dominio;
  /** Status HTTP. 0 = erro só do cliente (nunca vem da API). */
  status:          number;
  severidade:      Severidade;
  /** Texto mostrado ao usuário (pt-BR, sem jargão técnico). */
  mensagem:        string;
  /** O que o usuário deve fazer. */
  acao:            string;
  /** Como o sistema reage (retry, redirect, log, reembolso…). */
  reacao:          string;
  /** Explicação técnica, para gestão e suporte. */
  causa:           string;
  /** Repetir a mesma ação pode dar certo. */
  tentarNovamente: boolean;
}

function e(
  dominio: Dominio,
  status: number,
  severidade: Severidade,
  mensagem: string,
  acao: string,
  reacao: string,
  causa: string,
  tentarNovamente = false,
): ErrorDef {
  return { dominio, status, severidade, mensagem, acao, reacao, causa, tentarNovamente };
}

