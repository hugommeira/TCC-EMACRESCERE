export type ErrorCode = keyof typeof ERROS;

export function isErrorCode(code: unknown): code is ErrorCode {
  return typeof code === "string" && Object.prototype.hasOwnProperty.call(ERROS, code);
}

export function getErro(code: ErrorCode): ErrorDef {
  return ERROS[code];
}

/** Mensagem ao usuário para um código; cai no genérico se o código for desconhecido. */
export function mensagemDoCodigo(code: unknown, fallback?: string): string {
  if (isErrorCode(code) && ERROS[code].mensagem) return ERROS[code].mensagem;
  return fallback ?? ERROS.ERRO_INTERNO.mensagem;
}

